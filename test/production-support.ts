import { execFile } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import { initProject } from "../src/commands/init.js";
import { flowSchema } from "../src/schemas/flow.js";
import { projectSchema } from "../src/schemas/project.js";

export async function productionFixture(
  env: Record<string, string> = {},
  reuseBuild = false,
) {
  const directory = await mkdtemp(join(tmpdir(), "idiom-production-test-"));
  await initProject({ project: directory, yes: true });
  const reservation = createServer();
  await new Promise<void>((accept) =>
    reservation.listen(0, "127.0.0.1", accept),
  );
  const address = reservation.address();
  if (address === null || typeof address === "string")
    throw new Error("no port");
  const port = address.port;
  await new Promise<void>((accept) => reservation.close(() => accept()));
  let scripts = join(import.meta.dirname, "fixtures", "production-capture");
  if (reuseBuild) {
    await cp(scripts, join(directory, "scripts"), { recursive: true });
    scripts = join(directory, "scripts");
  }
  // Fixture paths are generated by mkdtemp and contain no shell metacharacters.
  const environment = {
    PORT: String(port),
    DATA_DIR: "$" + "{dataDir}",
    NEXT_PUBLIC_API_BASE: `http://127.0.0.1:${port}`,
    OUTPUT_DIR: "production-output",
    AUDIT_FILE: join(directory, "audit.jsonl"),
    ...env,
  };
  const project = projectSchema.parse({
    version: 1,
    app: { name: "Production fixture", framework: "other" },
    server: {
      build: "node -e 0",
      start: `node '${join(scripts, "server.mjs")}' development`,
      readyUrl: `http://127.0.0.1:${port}/`,
      port,
      env: environment,
      startupTimeoutMs: 3_000,
      production: {
        reuseBuild,
        build: `node '${join(scripts, "build.mjs")}'`,
        start: `node '${join(scripts, "server.mjs")}' production`,
        distDir: "production-output",
        env: environment,
      },
    },
    viewports: [{ name: "desktop", width: 800, height: 600 }],
    capture: { settleMs: 200 },
    design: {},
    model: { provider: "anthropic", model: "unused" },
  });
  const flow = flowSchema.parse({
    id: "fixture",
    title: "Fixture",
    setup: reuseBuild
      ? [{ run: `node '${join(scripts, "setup.mjs")}'`, env: environment }]
      : [],
    intent: [],
    states: [
      {
        id: "home",
        description: "Home",
        url: "/",
        expect: { textPresent: ["PRODUCTION MARKER", "CLIENT API OK"] },
      },
    ],
  });
  await writeFile(
    join(directory, ".idiom", "project.json"),
    JSON.stringify(project),
  );
  await writeFile(
    join(directory, ".idiom", "flows", "fixture.json"),
    JSON.stringify(flow),
  );
  const git = promisify(execFile);
  await git("git", ["init", "--quiet"], { cwd: directory });
  if (reuseBuild) {
    await writeFile(
      join(directory, ".gitignore"),
      "production-output/\naudit.jsonl\nunit-data/\n.idiom/reports/\n",
    );
    await git("git", ["add", "."], { cwd: directory });
  }
  await git(
    "git",
    [
      "-c",
      "user.name=Test",
      "-c",
      "user.email=test@example.com",
      "commit",
      "--allow-empty",
      "--quiet",
      "-m",
      "fixture",
    ],
    { cwd: directory },
  );
  const dataDirectory = join(directory, "unit-data");
  await mkdir(dataDirectory);
  return {
    directory,
    project,
    flow,
    dataDirectory,
    audit: async () =>
      (await readFile(join(directory, "audit.jsonl"), "utf8"))
        .trim()
        .split("\n")
        .map(
          (line) =>
            JSON.parse(line) as {
              phase: string;
              pid: number;
              port: string;
              data: string;
              api?: string;
              marker?: string;
            },
        ),
  };
}
